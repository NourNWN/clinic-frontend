/** Maps a category (by its English name) to a fitting icon. */
export function categoryIcon(nameEn) {
  const key = nameEn.toLowerCase();
  if (key.includes("inject")) return "syringe";
  if (key.includes("laser")) return "zap";
  if (key.includes("skin")) return "droplet";
  if (key.includes("facial") || key.includes("face")) return "smile";
  return "sparkles";
}
